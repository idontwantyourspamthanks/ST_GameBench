        lea     MTAB.l,a0
        moveq   #0,d5
        move.b  d4,d5
        andi.w  #$f,d5
        add.w   d5,d5
        add.w   d5,d5
        move.l  (a0,d5.w),d6            ; MA: plane bytes selected by d4 bits 0-3
        moveq   #0,d5
        move.b  d4,d5
        lsr.b   #4,d5
        add.w   d5,d5
        add.w   d5,d5
        move.l  (a0,d5.w),d5            ; MB: bits 4-7
        subq.w  #1,d7
        movea.l a3,a0
.row:   moveq   #0,d1
        moveq   #0,d2
        move.b  (a1)+,d1
        move.b  (a1)+,d2
        add.w   d1,d1
        add.w   d1,d1
        add.w   d2,d2
        add.w   d2,d2
        move.l  (a2,d1.w),d1
        move.l  (a2,d2.w),d2
        movep.l 0(a0),d3
        move.l  d1,d0
        or.l    d2,d0
        not.l   d0
        and.l   d0,d3
        and.l   d6,d1
        and.l   d5,d2
        or.l    d1,d3
        or.l    d2,d3
        movep.l d3,0(a0)
        lea     160(a0),a0
        dbra    d7,.row
        movem.l (a7)+,d5-d6/a0/a2
        move.l  a3,d0
        addq.l  #7,d0
        andi.w  #$fff9,d0
        movea.l d0,a3
        rts

