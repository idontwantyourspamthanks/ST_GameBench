NOT_SHIPPABLE = {"test_poke"}


def chosen_patches(only):
    allp = nepatch.load_patches()
    sel = nepatch.chosen(only, allp)
    bad = [p.name for p in sel if p.name in NOT_SHIPPABLE]
    if bad:
        raise SystemExit(f"{bad}: test patches are not shipped")
    miss = [p.name for p in sel if p.name not in DOCS]
    if miss:
        raise SystemExit(f"no user text in tools/nebrelease.py DOCS for {miss}: describe them before releasing")
    return sel


def render(text, sel, ram, stamp):
    short = "\n".join("  * " + DOCS[p.name][0] for p in sel)
    parts = []
    for p in sel:
        parts.append(f"{p.name}\n" + textwrap.fill(" ".join(DOCS[p.name][1].replace("@VERSION@", version()).split()), 78, initial_indent="  ", subsequent_indent="  "))
        for ad, new in p.sites:
            o = bytes(ram[ad:ad + len(new)])
            if len(new) > 16:
                parts.append(f"    ${ad:06x}  {len(new)} bytes of new code in spare game RAM (written unconditionally; the patch tables are only for the README now)")
            else:
                parts.append(f"    ${ad:06x}  {o.hex()} -> {new.hex()}")
        for ad, data in p.blocks:
            parts.append(f"    ${ad:06x}  {len(data)} bytes of code/data in free RAM")
        parts.append("")
    ed = any(p.name == "ed_overlay" for p in sel)
    text = re.sub(r"@@EDITOR\n(.*?)@@END\n\n?", (lambda m: m.group(1) + "\n") if ed else "", text, flags=re.S)
    text = (text.replace("{WHATSNEW}", short).replace("{PATCHES}", "\n".join(parts).rstrip())
            .replace("@VERSION@", version()).replace("{GIT}", stamp))
    return text


def pp_readme() -> str:
    return (ORIG / "README.TXT").read_bytes().decode("latin-1").replace("\r\n", "\n")


def wrap(text: str, width: int = 78) -> str:
    """Hard-wrap over-long lines at `width`, keeping the leading indent (+2 under a `* ` bullet); short lines are untouched."""
    import textwrap
    out = []
    for ln in text.split("\n"):
        if len(ln) <= width or ln.startswith("-" * 20):
            out.append(ln); continue
        ind = ln[:len(ln) - len(ln.lstrip())]
        sub = ind + ("  " if ln.lstrip().startswith("* ") else "")
        out += textwrap.wrap(ln, width, initial_indent="", subsequent_indent=sub, break_long_words=False, break_on_hyphens=False, drop_whitespace=True) or [ln]
    return "\n".join(out)


def crlf(t: str) -> bytes:
    return t.replace("\r\n", "\n").replace("\n", "\r\n").encode("latin-1")


def build(out: Path, only, make_zip: bool) -> Path:
    gen_credit()
    sel = chosen_patches(only)
    names = [p.name for p in sel]
    ram = nepatch.predicted_stage2()
    ns = argparse.Namespace(out=str(out), only=names, corrupt=False, fill=False, ovl=None)
    nepatch.cmd_build(ns)
    stamp = git_stamp()
    if "ed_overlay" not in names:
        (out / nepatch.OVLN).unlink(missing_ok=True)
    else:
        import nebcampaign                  # blank campaign disk (720 KB, all-zero NEBLEVEL.OVL): the editor's load/save medium in drive A:
        (out / "Nebulus_campaign_disk.st").write_bytes(nebcampaign.build())
    readme = render((PATCHES / "README_HD.TXT").read_text(), sel, ram, stamp)
    readme += "\n\n" + "-" * 78 + "\nPP's README.TXT of the original Gamex conversion (unchanged):\n" + "-" * 78 + "\n" + pp_readme()
    (out / "README.TXT").write_bytes(crlf(wrap(readme)))
    (out / "PATCHES.TXT").write_bytes(crlf(wrap(render((PATCHES / "PATCHES.TXT").read_text(), sel, ram, stamp))))
    print("patches:", ", ".join(names), "| stamp:", stamp)
    if make_zip:
        DIST.mkdir(exist_ok=True)
        z = DIST / f"Nebulus_hd_v{version()}.zip"
        dt = commit_time()
        with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
            for f in sorted(out.iterdir()):
                zi = zipfile.ZipInfo(f"{FOLDER}/{f.name}", date_time=dt)
                zi.compress_type = zipfile.ZIP_DEFLATED
                zi.external_attr = 0o644 << 16
                zf.writestr(zi, f.read_bytes())
        print(f"zip {z} {z.stat().st_size} B md5 {hashlib.md5(z.read_bytes()).hexdigest()}")
    return out


