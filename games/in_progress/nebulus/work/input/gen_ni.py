"""Generate patches/ni_latch.nep from patches/ni_latch.s (vasm -Fbin -m68000 -no-opt)."""
import sys, subprocess, tempfile
from pathlib import Path
G = Path(__file__).resolve().parents[2]
P = G / 'patches'
src = (P / 'ni_latch.s').read_text()
with tempfile.TemporaryDirectory() as d:
    s = Path(d) / 'a.s'; o = Path(d) / 'a.bin'; s.write_text(src)
    subprocess.run(['vasmm68k_mot', '-Fbin', '-m68000', '-no-opt', '-o', str(o), str(s)], check=True, capture_output=True)
    blob = o.read_bytes()
assert len(blob) % 2 == 0
(P / 'ni_latch.nep').write_text(f"""# Nebulus input fix B (NebInput2), DEFAULT ON: sticky fire latch. A fire press whose release byte arrives before the game's next poll
# (the cell $38498 is level-sampled once per game loop = every 2 VBL) is no longer lost. Source patches/ni_latch.s; generated by work/input/gen_ni.py.
# Blob ({len(blob)} bytes at $76d00, inside the verified-zero gap; the trainer blob uses $76c00..$76c75):
#   $76d00 latch word | $76d04 stub1 (store the IKBD byte as before; if (byte & $f0) == $80 set the latch; jmp $3851a) | $76d22 stub2 (latch -> fire flag, once)
# clear $76d00..$76d03 = the latch word + pad: zeroed by the loader at every start, never assumed zero (work/notes/junkram.md).
# Two 6-byte sites (original bytes derived by nepatch from the predicted stage-2 image):
#   $38514 `move.b d0,$38498.l`  -> jmp $76d04      (ACIA store, also reached from the Gamex hook $200)
#   $3855a `move.w d1,$338f0.l`  -> jsr $76d22      (fire-flag store inside sub_03853a, joystick path only)
patch ni_latch
default yes
clear 76d00 4
site 38514 4ef900076d04
site 3855a 4eb900076d22
site 76d00 {blob.hex()}
""")
(P / 'ni_jump.nep').write_text("""# Nebulus input fix A (NebInput2), DEFAULT ON: remove the one-loop dead time of the fire jump.
# The walking-jump entry $39fc8 (fire pressed while walking) only sets player state $33a20=1, starts the jump sound/anim and `rts`; the first jump step
# (state-1 handler $3a026: y/pose/x) ran in the NEXT game loop, so the flip after the press showed an unchanged picture (+1 loop = 2 frames = 40 ms at the 2-VBL loop).
# The entry now branches into $3a026 so step 0 runs in the same loop. Per-flip player state is identical, one loop earlier (gate: work/notes/input.md). No blob.
#   $39ffa  4e75 (rts after jsr $33be8 of $39fc8)  -> 602a   bra.s $3a026
# NOT included: the blocked-walk auto-hop entry $39ffc (end $3a024), see ni_hop.nep.
patch ni_jump
default yes
site 39ffa 602a
""")
(P / 'ni_hop.nep').write_text("""# Nebulus input: dead-loop removal for the AUTO-HOP (walking into an obstacle, entry $39ffc, no fire needed), DEFAULT NO.
# Measured (work/notes/input.md, scenario j2): with this site the repeated hops of a blocked walk cycle every 9 loops instead of 10, i.e. stair/ledge climbing by
# holding the direction gets 11% faster. That is a gameplay-speed change, not only a latency change, so it is off by default.
#   $3a024  4e75 (rts at the end of $39ffc)  -> 4e71  nop (falls into $3a026)
patch ni_hop
default no
site 3a024 4e71
""")
print('ok', blob.hex())
