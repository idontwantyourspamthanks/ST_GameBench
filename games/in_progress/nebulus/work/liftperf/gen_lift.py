"""Generate patches/np_lift.nep from patches/np_lift.s: one site per `; ---- site ADDR` block (vasm -Fbin -m68000 -no-opt per block)."""
import re, subprocess, tempfile, sys
from pathlib import Path
G = Path(__file__).resolve().parents[2]
P = G / 'patches'
src = (P / 'np_lift.s').read_text()
blocks = re.split(r'^; ---- site ([0-9a-f]+)[^\n]*\n', src, flags=re.M)
head, rest = blocks[0], blocks[1:]
sites = []
for addr, body in zip(rest[0::2], rest[1::2]):
    with tempfile.TemporaryDirectory() as d:
        s = Path(d) / 'a.s'; o = Path(d) / 'a.bin'; s.write_text(body)
        subprocess.run(['vasmm68k_mot', '-Fbin', '-m68000', '-no-opt', '-o', str(o), str(s)], check=True, capture_output=True)
        b = o.read_bytes()
    sites.append((addr, b))
    print(addr, len(b), b.hex())
hdr = '\n'.join('# ' + l[2:] if l.startswith('; ') else '#' for l in head.splitlines())
default = 'yes' if (len(sys.argv) < 2 or sys.argv[1] != '--no') else 'no'
out = hdr + '\n# Generated by work/liftperf/gen_lift.py from patches/np_lift.s.  Original bytes are derived by nepatch from the predicted stage-2 image.\npatch np_lift\ndefault ' + default + '\n'
for a, b in sites: out += f'site {a} {b.hex()}\n'
(P / 'np_lift.nep').write_text(out)
