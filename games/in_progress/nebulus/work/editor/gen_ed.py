#!/usr/bin/env python3
"""Build step: assemble patches/ed_editor.s with vasm (branches written `.s` in the source are unsized here so vasm picks the size, with
optimisation on) and write patches/ed_overlay.nep (house format; original bytes are derived by nepatch).
Hook sites (replaced bytes are re-created at the start of each hook):
  $377a2 decode (6B, jmp)   $37a90 spawn dir (8B)   $3d6c4 title poll (10B)   $3adb4 time (6B)   $3d110 name (6B)   $3e352 tower complete (6B, jmp)   $3dfd6 flip (6B)   $3851a ACIA key latch (6B jmp)   $3d662 Options hint (8B)
Blocks (`block ADDR HEX`, unverified copy by core2) = the S-record segments of the assembly: code $75740.. (dead zone), tables $76d40..,
code $77300.., the lift block $77a40.., the disk block $77dc0.. and $76c76.. (zero gap; the code blocks stay clear of the trainers $76c00-$76c75, latch $76d00-$76d3b, credit $77a00-$77a3f
and the runtime state RS $77c80)."""
import re, subprocess, tempfile, sys
from pathlib import Path
G = Path(__file__).resolve().parents[2]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else G / "patches/ed_editor.s"       # optional: another source (debug builds) and output .nep
txt = src.read_text()
eq = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"^(\w+)\s+equ\s+\$([0-9a-f]+)", txt, re.M)}
txt2 = re.sub(r"\b(bra|bsr|b(?:eq|ne|cc|cs|hs|lo|hi|ls|mi|pl|ge|lt|gt|le|vc|vs))\.s\b", r"\1", txt)
with tempfile.TemporaryDirectory() as d:
    s = Path(d) / "e.s"; s.write_text(txt2); o = Path(d) / "e.srec"; l = Path(d) / "e.lst"
    r = subprocess.run(["vasmm68k_mot", "-Fsrec", "-m68000", "-L", str(l), "-o", str(o), str(s)], capture_output=True, text=True)
    if r.returncode:
        print(r.stdout + r.stderr); sys.exit(1)
    mem = {}
    for ln in o.read_text().splitlines():
        if ln.startswith("S3"):
            n = int(ln[2:4], 16); addr = int(ln[4:12], 16); data = bytes.fromhex(ln[12:12 + (n - 5) * 2])
            for i, b in enumerate(data):
                assert addr + i not in mem, f"overlapping segments at ${addr+i:x}"
                mem[addr + i] = b
    lst = l.read_text()
addrs = sorted(mem); segs = []
for a in addrs:
    if segs and segs[-1][0] + len(segs[-1][1]) == a:
        segs[-1][1].append(mem[a])
    else:
        segs.append((a, bytearray([mem[a]])))
segs = [(a, bytes(b)) for a, b in segs]
sym = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"^(\w+)\s+A:([0-9A-Fa-f]+)", lst, re.M)}
# segment table: name -> (start equ, limit).  CODE1 ends before the trainer blob; CODE5 sits in the gap behind it; DATA ends before the ni_ikbd blob $7726c..$772c5, CODE2 before the credit blob; CODE3 before RS; CODE4 before $77ec0
LIM = {"CODE1": 0x76C00, "CODE5": 0x76D00, "DATA": 0x7726C, "CODE2": 0x77A00, "CODE3": eq["RS"], "CODE4": 0x77EC0}
order = ["CODE1", "DATA", "CODE2", "CODE3", "CODE4", "CODE5"]
assert sorted(a for a, _ in segs) == sorted(eq[n] for n in order), [(hex(a), len(b)) for a, b in segs]
seg = {n: next(b for a, b in segs if a == eq[n]) for n in order}
for n in order:
    assert eq[n] + len(seg[n]) <= LIM[n], f"{n} ${eq[n]:x}+{len(seg[n])} ends at ${eq[n]+len(seg[n]):x} > limit ${LIM[n]:x}"
# non-overlap with the other default blobs: trainers $76c00-$76c75, latch $76d00-$76d3b, credit $77a00-$77a3f, state RS/V $77c80-$77dbf (private stack: $AD000, non-game)
for n in order:
    lo, hi = eq[n], eq[n] + len(seg[n])
    for blo, bhi, bw in ((0x76C00, 0x76C76, "trainers"), (0x76D00, 0x76D3C, "latch"), (0x77A00, 0x77A40, "credit"), (0x7726C, 0x772C6, "ni_ikbd blob"), (eq["RS"], 0x77DC0, "state RS/V")):
        assert hi <= blo or lo >= bhi, f"{n} ${lo:x}..${hi:x} overlaps {bw}"
free = {n: LIM[n] - eq[n] - len(seg[n]) for n in order}
(c1, d1), (c2, d2), (c3, d3), (c4, d4), (c5, d5), (c6, d6) = [(eq[n], seg[n]) for n in ("CODE1", "DATA", "CODE2", "CODE3", "CODE4", "CODE5")]
H = c1
def a(x): return f"{x:08x}"
nep = f"""# Nebulus campaign + level editor (NebEditor).  Generated by work/editor/gen_ed.py from patches/ed_editor.s; do not edit by hand.
# F10 (or D) on the title page = level/campaign manager + editor; F10 in a playtest = back to the editor.  See work/notes/editor.md.
# Sites: $377a2 decode hook, $37a90 spawn direction, $3d6c4 title poll, $3adb4 initial time, $3d110 tower name, $3e352 tower complete, $3dfd6 frame flip,
# clear: runtime state RS+V ($77c80..$77dbf, 320 B) is zeroed by the loader at every start (RAM is not zero on a MiSTer / after a warm reset; work/notes/junkram.md).
# $3851a ACIA-path key latch (the F10 make byte is not lost to the one-cell sampling; D is read from the cell), $3d662 Options-page hint line.
# Blocks (6): code1 {len(d1)} B at ${c1:x} (dead zone: relocation table remnants / NEBULTIT tail), tables {len(d2)} B at ${c2:x}, code2 {len(d3)} B at ${c3:x}, code3 {len(d4)} B at ${c4:x},
# code4 {len(d5)} B at ${c5:x}, code5 {len(d6)} B at ${c6:x} (zero gap; no overlap with the trainer blob $76c00-$76c75, latch $76d00-$76d3b, credit $77a00-$77a3f, state $77c80-$77dbf).
patch ed_overlay
default yes
clear {eq["RS"]:x} {eq["CODE4"] - eq["RS"]:x}
site 377a2 4ef9{a(H)}
site 37a90 4eb9{a(H+6)}4e71
site 3d6c4 4eb9{a(H+12)}4e714e71
site 3adb4 4eb9{a(H+18)}
site 3d110 4eb9{a(H+24)}
site 3e352 4ef9{a(H+30)}
site 3dfd6 4eb9{a(H+36)}
site 3851a 4ef9{a(sym["ed_key"])}
site 3d662 4ef9{a(sym["ed_opt"])}4e71
block {c1:x} {d1.hex()}
block {c2:x} {d2.hex()}
block {c3:x} {d3.hex()}
block {c4:x} {d4.hex()}
block {c5:x} {d5.hex()}
block {c6:x} {d6.hex()}
"""
(Path(sys.argv[2]) if len(sys.argv) > 2 else G / "patches/ed_overlay.nep").write_text(nep)
print("blocks: " + "; ".join(f"{n} ${eq[n]:x}..${eq[n]+len(seg[n]):x} {len(seg[n])} B (free {free[n]})" for n in order), f"| total {sum(len(seg[n]) for n in order)} B")
