; doc: Speech, part 3: the message-ticker glyph kernel (8 rows, ~3.7 k cycles, drawn twice per typed character) rewritten with MOVEP: ~1.8 k cycles; pixel-identical.
; note: Tighten wave A (work/notes/tighten_a.md).  Site $14fd4 = the stock one-colour/two-mask glyph kernel (`subq.w #1,d7 / movea.l a3,a4 / move.b (a1)+,d1`, 6 bytes) -> `jmp $BE600.l`.  Its only caller is the ticker's glyph routine $120a4 (jsr at $120cc; the alternative copy $1223c jumps to it too).
; note: Stock per row and plane k: byte new = (old and not(d1 or d2)) or (bit k of d4 ? d1 : 0) or (bit k+4 of d4 ? d2 : 0), d1/d2 = the two font bytes of the row, d4 = the colour byte of the message, a3 = the screen byte of plane 0, planes at +2 (a word per plane per 16 pixels).
; note: The blob does the same four plane bytes of a row with one MOVEP.L read and one MOVEP.L write (alternate bytes = the four planes), the masks built by a 256-entry replicate table ($BE800) and a 16-entry plane-select table ($BEC00).  Result a3 = (a3 + 7) and $fff9 exactly as the stock epilogue.
; note: Registers: stock clobbers d0-d4 d7 a1 a3 a4; the blob uses those plus d5 d6 a0 a2 (saved).  MOVEP exists on the 68000-68030; a 68060 would emulate it in software (no Moonshine target machine has one).
