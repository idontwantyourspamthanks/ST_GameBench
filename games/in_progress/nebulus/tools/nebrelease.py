def version() -> str:
    return (PATCHES / "VERSION").read_text().strip()


def git_stamp() -> str:
    """`git <short hash>` of HEAD, plus ' + uncommitted changes' when the files this release is built from differ from HEAD."""
    def g(*a):
        return subprocess.run(["git", "-C", str(GAME), *a], capture_output=True, text=True).stdout.strip()
    h = g("rev-parse", "--short", "HEAD")
    dirty = g("status", "--porcelain", "--", "patches", "tools")
    return f"git {h}" + (" + uncommitted changes" if dirty else "")


def commit_time() -> tuple:
    import time
    t = subprocess.run(["git", "-C", str(GAME), "log", "-1", "--format=%ct"], capture_output=True, text=True).stdout.strip()
    return time.gmtime(int(t))[:6]


# ---------------------------------------------------------------- credit patch
def gen_credit() -> Path:
    text = f"v{version()} enhanced by dad_prg"
    src = (PATCHES / "cr_credit.s").read_text().replace("@TEXT@", text)
    blob = nepatch.asm(CREDIT_ADDR, src)
    hook = nepatch.asm(0x3D698, f"\tjsr ${CREDIT_ADDR:x}.l\n\tnop\n")
    assert len(hook) == 8 and len(blob) % 2 == 0
    out = PATCHES / "cr_credit.nep"
    out.write_text(
        "# Nebulus release credit line (DEFAULT ON).  Generated by tools/nebrelease.py from patches/cr_credit.s + patches/VERSION; do not edit by hand.\n"
        f"# Prints \"{text}\" with the game's own title printer on the frog-on-a-plinth title page only (not High Scorers, not the options page).\n"
        f"# Hook: $3d698 `move.w #$fffe,$38212.l` (8 bytes, after the title page is drawn) -> jsr ${CREDIT_ADDR:x} / nop; the blob redoes the move, then\n"
        "# prints line 3 (screen row 144, the empty line between the copyright and \"Mission #n\") when the page word $3d5b6 is 0.\n"
        f"# Blob ({len(blob)} bytes at ${CREDIT_ADDR:x}, in the verified-zero gap between editor CODE2 and CODE3).\n"
        "patch cr_credit\ndefault yes\n"
        f"site 3d698 {hook.hex()}\n"
        f"site {CREDIT_ADDR:x} {blob.hex()}\n")
    return out


