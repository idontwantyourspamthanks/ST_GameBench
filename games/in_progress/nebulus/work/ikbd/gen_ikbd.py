"""Generate patches/ni_ikbd.nep from patches/ni_ikbd.s (vasm -Fbin -m68000 -no-opt). Refuses to write if the blob overlaps any other patch's site/block."""
import sys, subprocess, tempfile, glob
from pathlib import Path
G = Path(__file__).resolve().parents[2]
P = G / 'patches'
src = (P / 'ni_ikbd.s').read_text()
with tempfile.TemporaryDirectory() as d:
    s = Path(d) / 'a.s'; o = Path(d) / 'a.bin'; l = Path(d) / 'a.lst'; s.write_text(src)
    r = subprocess.run(['vasmm68k_mot', '-Fbin', '-m68000', '-no-opt', '-L', str(l), '-o', str(o), str(s)], capture_output=True, text=True)
    if r.returncode: sys.exit(r.stdout + r.stderr)
    blob = o.read_bytes()
assert len(blob) % 2 == 0
IK = 0x7726C
def asm(text):
    with tempfile.TemporaryDirectory() as d:
        s = Path(d) / 'a.s'; o = Path(d) / 'a.bin'; s.write_text(text)
        r = subprocess.run(['vasmm68k_mot', '-Fbin', '-m68000', '-no-opt', '-o', str(o), str(s)], capture_output=True, text=True)
        if r.returncode: sys.exit(r.stdout + r.stderr)
        return o.read_bytes()
drain = 0
wd = len(asm(src[:src.index('\nwd:') + 1]))
# overlap check against every other patch's sites and blocks
for f in sorted(glob.glob(str(P / '*.nep'))):
    if f.endswith('ni_ikbd.nep'):
        continue
    for ln in Path(f).read_text().splitlines():
        w = ln.split()
        if w and w[0] in ('site', 'block') and not ln.startswith('#'):
            a = int(w[1], 16); n = len(bytes.fromhex(''.join(w[2:])))
            if a < IK + len(blob) and IK < a + n:
                sys.exit(f'blob ${IK:x}+{len(blob)} overlaps {Path(f).name} {w[0]} ${a:x}+{n}')
(P / 'ni_ikbd.nep').write_text(f"""# Nebulus input stall fix (NebInputStall), DEFAULT ON: IKBD/ACIA resync. Source patches/ni_ikbd.s; generated by work/ikbd/gen_ikbd.py. Notes: work/notes/inputstall.md.
# STOCK BUG (present in PP's original): START runs with SR=$2700 from $35c until the game's init $38486 (~1.3 s, 66 VBL). A byte the IKBD sends in that window (key,
# joystick, mouse) stays in the ACIA with its IRQ line low; the game's init then clears the MFP pending bits and the MFP never sees another edge: ALL input is dead for the run.
# Blob ({len(blob)} bytes at ${IK:x}, the gap between the editor tables and CODE2, verified zero like the other blobs): ${IK + drain:x} drain | ${IK + wd:x} wd (watchdog) | heal.
#   $38486 `move.w #$2300,sr / bsr.w $33e84` (8 B) -> jmp drain / nop   : read the ACIA while RDRF/OVRN is set, then the original SR change and a tail jump to $33e84.
#   $3853a `movem.l d0-d1/a0,-(a7) / move.b $38498(pc),d0` (8 B) -> jmp wd / nop : the poll's entry; if the ACIA status shows RDRF/OVRN in main context, run the real handler
#          $384fc through a fake exception frame (self-heal within one poll), then the poll as before.
patch ni_ikbd
default yes
site 38486 4ef9{IK + drain:08x}4e71
site 3853a 4ef9{IK + wd:08x}4e71
site {IK:x} {blob.hex()}
""")
print('ok', len(blob), 'bytes; drain', hex(IK + drain), 'wd', hex(IK + wd))
print(blob.hex())
