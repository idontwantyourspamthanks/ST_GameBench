#!/usr/bin/env python3
"""Build step: assemble the trainer blob from patches/nt_keys.s with vasm and (re)write the .nep delivery files.
nepatch.py cannot run vasm on nt_*.s itself, so the blob bytes are embedded as hex in patches/nt_trainers.nep.
Run:  python3 work/train/gen_nep.py     (then: python3 tools/nepatch.py verify)
Everything is derived from nt_keys.s: the blob = the part from `org NT` on (with NT = $76c00); the three site words are
`jsr NT+off.l` (4eb9 + address) and the orig bytes are NOT written here (nepatch derives them from the predicted image)."""
import re, subprocess, tempfile
from pathlib import Path
G = Path(__file__).resolve().parents[2]
P = G / "patches"
NT = 0x76c00
src = (P / "nt_keys.s").read_text().splitlines()
i = next(n for n, l in enumerate(src) if re.match(r"\s*org\s+NT\s*$", l))
body = "\n".join(src[i:])
with tempfile.TemporaryDirectory() as d:
    s = Path(d) / "b.s"; o = Path(d) / "b.bin"
    s.write_text(f"NT equ ${NT:x}\n{body}\n")
    r = subprocess.run(["vasmm68k_mot", "-Fbin", "-no-opt", "-m68000", "-o", str(o), str(s)], capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr
    blob = o.read_bytes()
# offsets of the three hooks come from the source's own `org NT+$xx` lines
org_of = {}
for l in src:
    m = re.match(r"\s*org\s+NT\+\$([0-9a-f]+)", l)
    if m:
        last = int(m.group(1), 16)
    m = re.match(r"(nt_kb|nt_timer|nt_enemy):", l)
    if m:
        org_of[m.group(1)] = last
assert org_of == {"nt_kb": 8, "nt_timer": 0x40, "nt_enemy": 0x58}, org_of
(G / "work/train/nt_blob_nep.bin").write_bytes(blob)
def jsr(a): return "4eb9" + f"{a:08x}"
hexb = blob.hex()
nep = f"""# Nebulus trainers, toggle build (DEFAULT ON).  Generated by work/train/gen_nep.py from patches/nt_keys.s (+ nt_tmrhook.s / nt_enhook.s); do not edit by hand.
# Keys: T = freeze / unfreeze the level timer, E = remove / restore enemies (each press toggles; both start OFF, so the game is unchanged until a key is pressed).
# Blob ({len(blob)} bytes at ${NT:x}, inside the verified-zero gap $76b10..$77ec0) = vasm -Fbin -no-opt -m68000 of nt_keys.s from `org NT` on.
# clear $76c00..$76c07 = the flag cells (prev, frz, noen): zeroed by the loader at every start, never assumed zero (work/notes/junkram.md).
# Three 6-byte `jsr` sites (original bytes are derived by nepatch from the predicted stage-2 image and verified before anything is written):
#   $3dcf4  key poll `jsr $3853a.l`           -> jsr NT+$08   (frame-loop hook: original poll + T/E edge detect on $38498)
#   $3b0a4  timer tick head `tst.w $33938.l`  -> jsr NT+$40   (returns Z=1 while frozen)
#   $3792c  spawn head `move.w $33a20.l,d0`   -> jsr NT+$58   (E on: clear creature states $3398c..$33993, skip the spawn)
patch nt_trainers
default yes
clear {NT:x} 8
site 3dcf4 {jsr(NT + 8)}
site 3b0a4 {jsr(NT + 0x40)}
site 3792c {jsr(NT + 0x58)}
"""
nep += f"site {NT:x} {hexb}\n"
(P / "nt_trainers.nep").write_text(nep)
(P / "nt_freeze_static.nep").write_text("""# Static variant (default NO, conflicts with nt_trainers: same site area): level timer frozen from boot, no key, no blob.
# sub_03b0a4 (timer tick) starts `tst.w $33938.l / beq.w $3b0fa`; the opcode byte 67 (beq) becomes 60 (bra): the tick head is always skipped.
patch nt_freeze_static
default no
site 3b0aa 6000
""")
(P / "nt_noenemy_static.nep").write_text("""# Static variant (default NO, conflicts with nt_trainers: overlaps the spawn site $3792c): no enemies from boot, no key, no blob.
# sub_03792c (enemy spawn, one call per game-loop iteration) starts with `move.w $33a20.l,d0`; its first word becomes `rts`.
# "Clear the creature states at start": no site needed, the four state words $3398c..$33993 are zero at boot (game workspace is cleared at init) and
# nothing can set them once the spawn is skipped; this variant is not retroactive (use the toggle build for a mid-level E).
patch nt_noenemy_static
default no
site 3792c 4e75
""")
print(len(blob), "blob bytes;", org_of)
